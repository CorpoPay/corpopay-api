#!/usr/bin/env node
/**
 * Generate the Miro Enum Catalog (`corpopay/miro/boards/02-data-model/enum-catalog.md`)
 * from `prisma/schema.prisma`, so the document can't drift from the schema.
 *
 * Usage:  node scripts/generate-enum-catalog.mjs [outputPath]
 *         (default outputPath = ../miro/boards/02-data-model/enum-catalog.md;
 *          pass "-" to print to stdout instead)
 *
 * Run this after changing an enum in the schema, then commit the regenerated
 * catalog in `corpopay/miro`. Prose annotations that live in the doc but not in
 * the schema are kept via the `annotations` map below (do not remove).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(repoRoot, "prisma", "schema.prisma");
const defaultOut = join(repoRoot, "..", "miro", "boards", "02-data-model", "enum-catalog.md");
const outPath = process.argv[2] ?? defaultOut;

const schema = readFileSync(schemaPath, "utf8");

// Parse `enum Name { ... }` blocks, preserving order and ignoring comments.
const enums = [];
let current = null;
for (const raw of schema.split("\n")) {
  const line = raw.trim();
  if (!current) {
    const m = line.match(/^enum\s+([A-Za-z0-9_]+)\s*\{/);
    if (m) current = { name: m[1], values: [] };
    continue;
  }
  if (line === "}") {
    enums.push(current);
    current = null;
    continue;
  }
  if (line === "" || line.startsWith("//")) continue;
  const value = line.split("//")[0].trim();
  if (/^[A-Z0-9_]+$/.test(value)) current.values.push(value);
}

// Group AuditAction values by their stable prefix, in a readable order.
const actionGroups = [
  ["Provider config", "PROVIDER_CONFIG_"],
  ["Refunds", "REFUND_"],
  ["API keys", "API_KEY_"],
  ["Tenant", "TENANT_"],
  ["Users", "USER_"],
  ["Payment link", "PAYMENT_LINK_"],
  ["Subscription", "SUBSCRIPTION_"],
  ["Installment plan", "INSTALLMENT_PLAN_"],
  ["Installment agreement", "INSTALLMENT_AGREEMENT_"],
];

// Prose annotations kept in the doc but not derivable from the schema (factual).
const annotations = {
  Provider:
    '(NAPS / VPS / STRIPE implemented; PAYPAL and ADYEN "not yet implemented")',
};

function fmtEnum(entry) {
  if (entry.name === "AuditAction") {
    const used = new Set();
    const parts = [];
    for (const [label, prefix] of actionGroups) {
      const vals = entry.values.filter((v) => v.startsWith(prefix));
      vals.forEach((v) => used.add(v));
      if (vals.length) parts.push(`${label}: ${vals.map((v) => "`" + v + "`").join(" · ")}`);
    }
    const rest = entry.values.filter((v) => !used.has(v));
    if (rest.length) parts.push(`Other: ${rest.map((v) => "`" + v + "`").join(" · ")}`);
    return `## ${entry.name} (${entry.values.length} actions)\n\n${parts.join(" ")}\n`;
  }
  const values = entry.values.map((v) => "`" + v + "`").join(" · ");
  const note = annotations[entry.name] ? ` ${annotations[entry.name]}` : "";
  return `## ${entry.name}\n\n${values}${note}\n`;
}

const header = `# CorpoPay — Enum Catalog

Source: \`prisma/schema.prisma\`. Every status/role/provider enum and its values.
Generated by \`corpopay-api/scripts/generate-enum-catalog.mjs\` — do not edit by hand.

`;

// AuditAction last (it's the verbose grouped one); others in schema order.
const simple = enums.filter((e) => e.name !== "AuditAction");
const audit = enums.find((e) => e.name === "AuditAction");
const body = [...simple, ...(audit ? [audit] : [])].map(fmtEnum).join("\n");

const content = header + body;
if (outPath === "-") {
  process.stdout.write(content);
} else {
  writeFileSync(outPath, content);
  console.log(`wrote ${outPath} (${enums.length} enums)`);
}
